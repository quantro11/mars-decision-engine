  /**
   * Pick a dictionary string by an explicit language flag (truthy = Turkish) and fill {0}, {1}, ... placeholders.
   * Used by modules that already hold a `tr` boolean, so the same text table serves every language.
   * @param {*} trFlag truthy -> STRINGS.tr, falsy -> STRINGS.en
   * @param {string} key
   * @param {Array} [args]
   */
  function pick(trFlag, key, args) {
    const tbl = trFlag ? STRINGS.tr : STRINGS.en;
    const s = tbl[key] ?? STRINGS.en[key] ?? key;
    return args ? s.replace(/\{(\d+)\}/g, (m, i) => String(args[+i])) : s;
  }

