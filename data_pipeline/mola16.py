"""
Rebuild the elevation, slope and roughness layers from true 16-bit MOLA elevations
(raw/mola16_9216x4608.npy, written by download_mola16.py) and patch them into
web/layers_data.js, web/layers/{elev,slope,rough}.png and web/layers/meta.json.
All other layers (SWIM, TES, basemap) are left untouched, so the full raw dataset is not needed.

Why: the original Trek product is 8-bit (~115 m per level). Slopes computed from it are dominated by
quantisation steps. The 16-bit MEGDR mosaic has 1 m vertical resolution.

    python mola16.py
"""
import base64
import io
import json
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.join(HERE, "..", "web")
LAYERS = os.path.join(WEB, "layers")
SRC = os.path.join(HERE, "raw", "mola16_9216x4608.npy")
OUT_W, OUT_H = 2048, 1024
MARS_R = 3389500.0   # m (IAU-2000 volumetric mean radius, matching preprocess.py and web engine)
ELEV_MIN_M, ELEV_MAX_M = -8200.0, 21230.0   # unchanged browser encoding (app code relies on it)


def log(*a):
    print(*a, flush=True)


def slope_deg(elev):
    H, W = elev.shape
    lat = 90 - (np.arange(H) + 0.5) * 180 / H
    dy = np.pi * MARS_R / H
    dx = np.maximum((2 * np.pi * MARS_R / W) * np.cos(np.radians(lat)), 1.0)[:, None]
    # central differences with longitude wrap
    gx = (np.roll(elev, -1, 1) - np.roll(elev, 1, 1)) / (2 * dx)
    gy = np.gradient(elev, axis=0) / dy
    return np.degrees(np.arctan(np.hypot(gx, gy))).astype(np.float32)


def reduce_rows(a, fn):
    """(4608, 9216) -> (1024, 2048): each output cell covers 4.5 x 4.5 source px.
    Duplicate every source px 2x2 so each output cell is exactly 9 x 9 samples (equal weights)."""
    H, W = a.shape
    out = np.empty((OUT_H, OUT_W), np.float32)
    for y in range(OUT_H):
        band = a[(y * 9) // 2:((y + 1) * 9 + 1) // 2]            # source rows touching this output row
        band = np.repeat(np.repeat(band, 2, axis=0), 2, axis=1)   # 2x
        off = (y * 9) % 2
        band = band[off:off + 9]                                   # exactly 9 rows
        out[y] = fn(band.reshape(9, OUT_W, 9).transpose(1, 0, 2).reshape(OUT_W, 81))
    return out


def png_uri(arr, name):
    im = Image.fromarray(arr, mode="L")
    im.save(os.path.join(LAYERS, name + ".png"), optimize=True)
    buf = io.BytesIO()
    im.save(buf, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def main():
    elev = np.load(SRC).astype(np.float32)
    H, W = elev.shape
    assert (W, H) == (9216, 4608), elev.shape
    log(f"MOLA16 {W}x{H}  min {elev.min():.0f} m  max {elev.max():.0f} m")
    # published MOLA elevations of landing sites (mission landing-site papers)
    for n, la, lo, ref in [("Curiosity", -4.59, 137.44, -4501), ("Opportunity", -1.95, -5.53, -1385),
                           ("Spirit", -14.57, 175.47, -1935), ("Viking 1", 22.27, -47.95, -3627),
                           ("InSight", 4.50, 135.62, -2613)]:
        r = int((90 - la) / 180 * H); c = int((lo + 180) / 360 * W) % W
        log(f"  check {n:13s} {elev[r, c]:8.0f} m   published ~{ref} m")

    log("slope (2.3 km grid, 16-bit)")
    sl = slope_deg(elev)
    slope_p90 = reduce_rows(sl, lambda b: np.percentile(b, 90, axis=1))
    rough = reduce_rows(elev, lambda b: b.std(axis=1))
    elev_out = reduce_rows(elev, lambda b: b.mean(axis=1))
    log(f"  slope p90 median {np.median(slope_p90):.2f} deg, 99th pct {np.percentile(slope_p90, 99):.1f}")
    log(f"  roughness median {np.median(rough):.0f} m")

    v8 = np.clip(np.round((elev_out - ELEV_MIN_M) / (ELEV_MAX_M - ELEV_MIN_M) * 255), 0, 255).astype(np.uint8)
    sl8 = np.clip(np.round(slope_p90 * 8), 0, 255).astype(np.uint8)
    ro8 = np.clip(np.round(rough / 4), 0, 255).astype(np.uint8)

    js = os.path.join(WEB, "layers_data.js")
    lines = open(js, encoding="utf-8").read().split("\n")
    meta = json.loads(lines[1][len("window.LAYER_META = "):].rstrip(";"))
    data = json.loads(lines[2][len("window.LAYER_DATA = "):].rstrip(";"))
    data["elev"], data["slope"], data["rough"] = png_uri(v8, "elev"), png_uri(sl8, "slope"), png_uri(ro8, "rough")
    src = "MOLA MEGDR 16-bit mosaic (USGS Astrogeology Mars_MGS_MOLA_DEM_mosaic_global_463m), sampled to 9216x4608 (~2.3 km/px)"
    meta["elev"]["source"] = src + "; browser storage 8-bit -8200..21230 m (~115 m/level, cell mean)"
    meta["slope"]["source"] = "derived: 90th percentile of slope computed on the 16-bit 9216x4608 MOLA grid inside each output cell (81 samples)"
    meta["rough"]["source"] = "derived: std-dev of 16-bit MOLA elevation inside each output cell (81 samples)"
    meta["generated_by"] = "data_pipeline/preprocess.py + data_pipeline/mola16.py (elev/slope/rough)"
    with open(js, "w", encoding="utf-8") as f:
        f.write("// Generated by data_pipeline/preprocess.py + mola16.py - do not edit by hand.\n")
        f.write("window.LAYER_META = " + json.dumps(meta) + ";\n")
        f.write("window.LAYER_DATA = " + json.dumps(data) + ";\n")
    full = json.load(open(os.path.join(LAYERS, "meta.json"), encoding="utf-8"))
    for k in ("elev", "slope", "rough", "generated_by"):
        full[k] = meta[k]
    with open(os.path.join(LAYERS, "meta.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(full, f, indent=2)
    with open(os.path.join(LAYERS, "meta.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated from layers/meta.json - layer scaling and provenance.\n")
        f.write("window.LAYER_META = " + json.dumps(full) + ";\n")
    log("patched", os.path.abspath(js))


if __name__ == "__main__":
    main()
